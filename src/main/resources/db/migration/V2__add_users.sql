-- Individual logins: every check-in belongs to one user. Existing rows keep user_id NULL until the app adopts them
-- for the first configured user at startup (see UserService.adoptOrphans).
CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(40) NOT NULL UNIQUE,
    music_enabled BOOLEAN     NOT NULL DEFAULT TRUE
);

ALTER TABLE check_in ADD COLUMN user_id BIGINT;
ALTER TABLE check_in ADD CONSTRAINT fk_check_in_user
    FOREIGN KEY (user_id) REFERENCES app_user (id) ON DELETE CASCADE;
CREATE INDEX idx_check_in_user_created ON check_in (user_id, created_at);
