-- Mood check-ins. Only the chosen emotions are stored, never the text the user typed.
CREATE TABLE check_in (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_check_in_created_at ON check_in (created_at);

CREATE TABLE check_in_emotion (
    check_in_id BIGINT      NOT NULL REFERENCES check_in (id) ON DELETE CASCADE,
    emotion     VARCHAR(32) NOT NULL,
    PRIMARY KEY (check_in_id, emotion)
);
